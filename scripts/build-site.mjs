// Generate every page from data. Run: node scripts/build-data.mjs && node scripts/build-site.mjs
import fs from 'node:fs';
import path from 'node:path';
import { crossFlags } from '../research/flags.mjs';

const root = path.resolve(import.meta.dirname, '..');
const entries = JSON.parse(fs.readFileSync(path.join(root, 'data/entries.json'), 'utf8'));
const stats = JSON.parse(fs.readFileSync(path.join(root, 'data/stats.json'), 'utf8'));
const CATEGORIES = stats.categories;
const healthPath = path.join(root, 'data/link-health.json');
const linkHealth = fs.existsSync(healthPath) ? JSON.parse(fs.readFileSync(healthPath, 'utf8')) : null;
const healthMap = linkHealth ? linkHealth.results : null;

const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const write = (rel, html) => {
  const p = path.join(root, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, html);
};
const byId = new Map(entries.map((e) => [e.id, e]));
const verified = entries.filter((e) => e.status === 'verified');
const ranked = verified.slice().sort((a, b) => (b.fit?.score ?? 0) - (a.fit?.score ?? 0));
const catName = (id) => CATEGORIES.find((c) => c.id === id)?.name || id;
const hardFail = entries.filter((e) => e.link?.hardFail);
const softFail = entries.filter((e) => e.link && !e.link.ok && !e.link.hardFail);

/* ---------------------------------------------------------------- layout */

