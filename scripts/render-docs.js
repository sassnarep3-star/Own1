#!/usr/bin/env node
/**
 * render-docs.js — write docs/EXECUTIVE_SUMMARY.md from the same content module that renders
 * the site's Executive summary page, so the document and the page can never disagree.
 *
 * Usage: node scripts/render-docs.js
 */
'use strict';

const fs = require('fs');
const path = require('path');
const content = require('./content');

const ROOT = path.resolve(__dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const ledger = read('data/ledger.json');
const verif = read('data/verification.json');
const irr = read('data/irregularities.json');

const ctx = {
  totals: verif.totals,
  flags: irr.items,
  verifiedOn: verif.verifiedOn,
  updatedOn: verif.rows.reduce((max, r) => r.crossCheck && r.crossCheck.checkedDate > max ? r.crossCheck.checkedDate : max, verif.verifiedOn),
  sourceReviewed: verif.sourceReviewed,
  commit: ledger.provenance.sourceRepoCommit,
  sha256: ledger.provenance.sourceFileSha256,
  flagCounts: Object.fromEntries(irr.items.map((f) => [f.id, (f.affected || []).length])),
  catCount: Object.fromEntries(ledger.types.map((t) => [t.id, ledger.listings.filter((i) => i.type === t.id).length]))
};

const c = content.build(ctx);

function md() {
  const out = [];
  out.push('# Executive summary');
  out.push('');
  out.push('_Updated ' + c.updatedOn + '; base verification snapshot ' + ctx.verifiedOn + '._');
  out.push('');
  out.push('_' + c.standfirst + '_');
  out.push('');
  for (const b of c.blocks) {
    if (b.t === 'h2') { out.push('', '## ' + b.text, ''); continue; }
    if (b.t === 'h3') { out.push('', '### ' + b.text, ''); continue; }
    if (b.t === 'p') { out.push(b.text, ''); continue; }
    if (b.t === 'ul') { b.items.forEach((i) => out.push('- ' + i)); out.push(''); continue; }
    if (b.t === 'ol') { b.items.forEach((i, n) => out.push(n + 1 + '. ' + i)); out.push(''); continue; }
    if (b.t === 'table') {
      out.push('| ' + b.head.join(' | ') + ' |');
      out.push('| ' + b.head.map(() => '---').join(' | ') + ' |');
      b.rows.forEach((r) => out.push('| ' + r.join(' | ') + ' |'));
      out.push('');
      continue;
    }
    if (b.t === 'links') {
      b.items.forEach((x) => {
        const url = /^https:\/\//.test(x.url) ? x.url : '../' + x.url;
        out.push('- [' + x.label + '](' + url + ') — ' + x.note);
      });
      out.push('');
      continue;
    }
  }
  out.push('---', '');
  out.push('Generated by `scripts/render-docs.js` for the verification date ' + verif.verifiedOn + '.');
  out.push('Site: https://sassnarep3-star.github.io/Own1/');
  out.push('');
  out.push('Every figure in this document is computed from `data/ledger.json`, `data/verification.json`');
  out.push('and `data/irregularities.json` at build time. Source dataset: commit `' + ctx.commit + '`,');
  out.push('SHA-256 `' + ctx.sha256 + '`.');
  return out.join('\n');
}

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/EXECUTIVE_SUMMARY.md'), md());
console.log('wrote docs/EXECUTIVE_SUMMARY.md');
