#!/usr/bin/env node
/**
 * render-docs.js — write docs/EXECUTIVE_SUMMARY.md from the same content module that
 * renders the live Executive summary page, so the document and the page always agree.
 *
 * Usage: node scripts/render-docs.js
 */
'use strict';

const fs = require('fs');
const path = require('path');
const content = require('./summary-content');

const ROOT = path.resolve(__dirname, '..');
const c = content.build();

function md() {
  const out = [];
  out.push('# Executive summary');
  out.push('');
  out.push('_' + c.standfirst + '_');
  out.push('');
  out.push('Verified on 2026-11-02. Live site: https://sassnarep3-star.github.io/Own1/');
  out.push('');
  for (const b of c.blocks) {
    if (b.t === 'h2') { out.push('', '## ' + b.text, ''); continue; }
    if (b.t === 'h3') { out.push('', '### ' + b.text, ''); continue; }
    if (b.t === 'p') { out.push(b.text, ''); continue; }
    if (b.t === 'ul') { b.items.forEach((i) => out.push('- ' + i)); out.push(''); continue; }
    if (b.t === 'ol') { b.items.forEach((i, n) => out.push((n + 1) + '. ' + i)); out.push(''); continue; }
    if (b.t === 'table') {
      out.push('| ' + b.head.join(' | ') + ' |');
      out.push('| ' + b.head.map(() => '---').join(' | ') + ' |');
      b.rows.forEach((r) => out.push('| ' + r.map((x) => String(x).replace(/\|/g, '\\|')).join(' | ') + ' |'));
      out.push('');
    }
  }
  out.push('---', '');
  out.push('Generated by `scripts/render-docs.js` from `scripts/summary-content.js`, which also renders `executive-summary.html`.');
  out.push('Every figure is computed at build time from `data/ledger.json`, `data/verification.json`,');
  out.push('`data/irregularities.json`, `data/verification-2026-11-02.json` and `data/review-2026-11-02.json`.');
  out.push('');
  return out.join('\n');
}

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/EXECUTIVE_SUMMARY.md'), md());
console.log('wrote docs/EXECUTIVE_SUMMARY.md');
